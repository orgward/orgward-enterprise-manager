import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

const contextPath = process.env.ORGWARD_CONTEXT_PATH;
if (!contextPath) throw new Error('ORGWARD_CONTEXT_PATH is required.');
const context = JSON.parse(await readFile(contextPath, 'utf8'));
const objective = String(context.workItem?.objective ?? '').trim();
if (!objective) throw new Error('The approved work item has no objective.');

const slug = objective.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '').slice(0, 48) || 'generated-service';
const serviceName = `${slug}-service`;
await mkdir('src', { recursive: true });
await mkdir('test', { recursive: true });

const serverSource = `import { createServer } from 'node:http';

export function createApp() {
  return createServer((request, response) => {
    if (request.url === '/health') {
      response.writeHead(200, { 'content-type': 'application/json' });
      return response.end(JSON.stringify({ status: 'ok', service: ${JSON.stringify(serviceName)} }));
    }
    response.writeHead(200, { 'content-type': 'application/json' });
    response.end(JSON.stringify({ service: ${JSON.stringify(serviceName)}, objective: ${JSON.stringify(objective)} }));
  });
}

if (process.argv[1] && import.meta.url.endsWith(process.argv[1])) {
  createApp().listen(Number(process.env.PORT || 3000), process.env.HOST || '127.0.0.1');
}
`;

const testSource = `import assert from 'node:assert/strict';
import test from 'node:test';
import { createApp } from '../src/server.mjs';

test('generated service exposes health', async (t) => {
  const server = createApp();
  await new Promise((resolve) => server.listen(0, '127.0.0.1', resolve));
  t.after(() => new Promise((resolve) => server.close(resolve)));
  const response = await fetch(\`http://127.0.0.1:\${server.address().port}/health\`);
  assert.equal(response.status, 200);
  assert.equal((await response.json()).status, 'ok');
});
`;

const files = {
  'package.json': `${JSON.stringify({ name: serviceName, version: '0.1.0', private: true, type: 'module', scripts: { start: 'node src/server.mjs', test: 'node --test' }, engines: { node: '>=22' } }, null, 2)}\n`,
  'src/server.mjs': serverSource,
  'test/service.test.mjs': testSource,
  'README.md': `# ${serviceName}\n\nGenerated by an approved OrgWard execution run.\n\n## Objective\n\n${objective}\n\n## Run\n\n\`\`\`bash\nnpm test\nnpm start\n\`\`\`\n`,
  'orgward-manifest.json': `${JSON.stringify({ schemaVersion: 1, generator: 'orgward-scaffold-node-service', contextHash: context.contentHash, workItemId: context.workItem.id, objective, requirements: context.contextPackage?.requirements ?? [], approval: context.contextPackage?.approval ?? null }, null, 2)}\n`,
  'Dockerfile': `FROM node:22-alpine\nWORKDIR /app\nCOPY . .\nUSER node\nEXPOSE 3000\nCMD ["node", "src/server.mjs"]\n`,
};

for (const [relative, content] of Object.entries(files)) {
  const target = path.resolve(relative);
  if (!target.startsWith(`${process.cwd()}${path.sep}`)) throw new Error('Generated path escaped the workspace.');
  await writeFile(target, content, { encoding: 'utf8', flag: 'wx', mode: 0o600 });
}
process.stdout.write(`created ${serviceName} with ${Object.keys(files).length} traced artifacts\n`);
